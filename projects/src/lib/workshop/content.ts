export interface WjTable {
  caption?: string;
  head: string[];
  rows: string[][];
  note?: string;
}

export interface WjFact {
  label: string;
  value: string;
  note?: string;
}

export interface WjInputOption {
  key: string;
  text: string;
}

/**
 * 小问的作答形式：缺省为文本作答（问答）。
 * ordering 分层排序，choice 单选，multi 多选，judge 逐条判断正误，matching 左右匹配；
 * choice/multi 的 withNote 为 true 时附一个补充说明框（理由/依据由它承载）。
 */
export type WjPartInput =
  | { type: 'ordering'; items: string[] }
  | { type: 'choice'; options: WjInputOption[]; withNote?: boolean }
  | { type: 'multi'; options: WjInputOption[]; withNote?: boolean }
  | { type: 'matching'; left: WjInputOption[]; right: WjInputOption[] };

export interface WjPart {
  label: string;
  text: string;
  tag?: string;
  input?: WjPartInput;
}

export interface WjQuestion {
  id: string;
  kind: string;
  stem: string;
  table?: WjTable;
  parts: WjPart[];
}

export interface WjStage {
  id: number;
  ordinal: string;
  name: string;
  tagline: string;
  /** 轻量环节只设两道细问，不与其余环节强求对称 */
  light?: boolean;
  /** 关键数据节的示意图版：AI 生成，图题必须带「示意」，不冒充真实文物照片 */
  figure?: { src: string; caption: string };
  why: string[];
  facts: WjFact[];
  tables: WjTable[];
  questions: WjQuestion[];
}

